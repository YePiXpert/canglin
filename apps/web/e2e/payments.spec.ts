import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('付款工作台：跨申请、批量修改、组合筛选、发票附件、导出与手机操作', async ({ page }) => {
  const password = 'browser-test-password', stamp = `PAY-${randomUUID()}`;
  await page.request.post('/api/auth/setup', { data: { password } });
  await page.request.post('/api/auth/login', { data: { password } });
  const post = async (path: string, data: object) => {
    const r = await page.request.post(`/api/${path}`, { data, headers: { 'Idempotency-Key': randomUUID() } });
    expect(r.ok(), await r.text()).toBeTruthy(); return r.json();
  };
  const a = await post('suppliers', { name: `${stamp}-供应商甲` }), b = await post('suppliers', { name: `${stamp}-供应商乙` });
  const request = async (suffix: string) => post('workflow/requests', { serialNumber: `${stamp}-${suffix}`, department: '行政', handler: '验收', requestDate: '2026-06-01', lines: [{ itemName: `${stamp}-纸`, specification: '', unit: '包', quantity: '10' }] });
  const r1 = await request('A'), r2 = await request('B');
  const p1 = await post('workflow/purchases', { date: '2026-06-02', supplierId: a.id, lines: [{ requestLineId: r1.lines[0].id, quantity: '1', unitPrice: '5' }, { requestLineId: r2.lines[0].id, quantity: '1', unitPrice: '6' }] });
  const p2 = await post('workflow/purchases', { date: '2026-06-03', supplierId: b.id, lines: [{ requestLineId: r1.lines[0].id, quantity: '1', unitPrice: '7' }] });
  await page.goto(`/insights/payments?search=${stamp}&paymentStatus=UNPAID`);
  const rows = page.locator('tr[data-payment-id]');
  await expect(rows).toHaveCount(2);
  const first = page.locator(`[data-payment-id="${p1.id}"]`);
  await expect(first.getByRole('link')).toHaveCount(2);
  await page.getByLabel('选择本页', { exact: true }).check();
  await page.getByRole('button', { name: '批量付款状态', exact: true }).click();
  const batch = page.getByRole('dialog', { name: '批量修改付款状态' });
  await expect(batch).toContainText('将 2 张采购单');
  await batch.getByRole('button', { name: '确认批量修改' }).click();
  await expect(rows).toHaveCount(0);
  await page.getByRole('combobox', { name: '付款状态筛选' }).selectOption('PAID');
  await page.getByRole('button', { name: '查询采购', exact: true }).click();
  await expect(rows).toHaveCount(2);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出筛选结果 CSV' }).click();
  const stream = await (await download).createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv).toContain(`${stamp}-A；${stamp}-B`); expect(csv).toContain('已付款');
  await page.setViewportSize({ width: 390, height: 844 });
  await first.getByRole('button', { name: `处理采购 #${p1.id} 的付款与发票` }).click();
  const dialog = page.getByRole('dialog', { name: '付款与发票', exact: true });
  await dialog.getByLabel('已开具发票').check();
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==', 'base64');
  await dialog.getByLabel('选择单据附件').setInputFiles({ name: '付款验收发票.png', mimeType: 'image/png', buffer: png });
  await expect(dialog.getByRole('link', { name: '付款验收发票.png' })).toBeVisible();
  await dialog.getByRole('button', { name: '保存付款与发票信息' }).click();
  await expect(first).toContainText('已开票'); await expect(first).toContainText('1 份发票附件');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('payments-mobile.png'), fullPage: true });
  await first.getByRole('link', { name: `${stamp}-B`, exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/requests/${r2.id}$`));
  await expect(page.getByRole('button', { name: new RegExp(`采购 #${p1.id}.*已付款.*已开票`) })).toBeVisible();
  const after = await (await page.request.get(`/api/workflow/documents/${p2.id}`)).json();
  expect(after.totalAmount).toBe('7.00'); expect(after.lines[0].quantity).toBe('1');
});
