import { afterAll, beforeAll, it, expect } from 'vitest';
import { randomUUID } from 'node:crypto';
import { quantityUnits } from '@canglin/shared';
import { createApp, closeApp, type TestApp } from './utils';
import { PrismaService } from '../src/prisma/prisma.service';
import { ReplenishmentService } from '../src/workflow/replenishment.service';
import { StocktakeService } from '../src/workflow/stocktake.service';
import { todayString } from '../src/common/date.util';
let ctx: TestApp;
beforeAll(async () => { ctx = await createApp(); });
afterAll(() => closeApp(ctx));
it('千级物品、万条流水下计算补货，200行盘点在事务上限内完整记账', async () => {
  const db = ctx.app.get(PrismaService), counts = ctx.app.get(StocktakeService), supply = ctx.app.get(ReplenishmentService);
  await db.catalogProduct.createMany({ data: Array.from({ length: 1000 }, (_, i) => ({ name: `规模物品-${i}`, unit: '件', stockVersion: 10 })) });
  const products = await db.catalogProduct.findMany({ orderBy: { id: 'asc' } });
  const doc = await db.businessDocument.create({ data: { kind: 'ADJUSTMENT', date: todayString() } });
  await db.businessLine.createMany({ data: products.map(p => ({ documentId: doc.id, productId: p.id, itemName: p.name, unit: p.unit, quantityUnits: quantityUnits('10'), location: 'STOCK' })) });
  const lines = await db.businessLine.findMany({ where: { documentId: doc.id }, orderBy: { id: 'asc' } });
  await db.stockBalance.createMany({ data: lines.map(l => ({ productId: l.productId, originLineId: l.id, location: 'STOCK', quantityUnits: quantityUnits('10') })) });
  for (let i = 0; i < 10; i++) await db.stockEntry.createMany({ data: lines.map(l => ({ productId: l.productId, originLineId: l.id, businessLineId: l.id, location: 'STOCK', quantityUnits: quantityUnits('1'), date: todayString() })) });
  await db.stockPolicy.createMany({ data: products.map(p => ({ productId: p.id, enabled: true, minimumUnits: quantityUnits('15'), targetUnits: quantityUnits('20') })) });
  const start = performance.now();
  const suggestions = await supply.suggestions(); expect(suggestions).toHaveLength(1000); expect(suggestions.every(s => s.suggested === '10')).toBe(true);
  const queryMs = Math.round(performance.now() - start);
  const c = await counts.create({ title: '200行盘点', note: '', productIds: products.slice(0,200).map(p => p.id) }, randomUUID());
  const saved = await counts.save(c.id, { version: c.version, title: c.title, note: '', lines: c.lines.map(l => ({ productId: l.productId, actualQuantity: '9.5', reason: '实盘' })) }, randomUUID());
  const postStart = performance.now(), posted = await counts.post(c.id, { version: saved.version }, randomUUID());
  const postMs = Math.round(performance.now() - postStart);
  expect(posted.lines).toHaveLength(200); expect(posted.lines.every(l => l.currentQuantity === '9.5')).toBe(true);
  expect(await db.stockEntry.count()).toBe(10200); expect(postMs).toBeLessThan(30_000);
  console.info(`规划规模验收：1000物品/10000流水，建议 ${queryMs}ms，200行记账 ${postMs}ms`);
}, 60_000);
