import { afterAll, beforeAll, expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import { executionQuerySchema } from '@canglin/shared';
import { createApp, closeApp, type TestApp } from './utils';
import { PrismaService } from '../src/prisma/prisma.service';
import { FinanceService } from '../src/execution/finance.service';
import { BatchesService } from '../src/execution/batches.service';
let ctx: TestApp;
beforeAll(async () => { ctx = await createApp(); });
afterAll(() => closeApp(ctx));
it('千张采购与万条付款下分页金额准确，200行集中采购整批确认', async () => {
  const db = ctx.app.get(PrismaService), finance = ctx.app.get(FinanceService), batches = ctx.app.get(BatchesService), date = '2026-10-23';
  const supplier = await db.supplier.create({ data: { name: '规模供应商' } });
  await db.catalogProduct.createMany({ data: Array.from({ length: 1000 }, (_, i) => ({ name: `对账物品-${i}`, unit: '件' })) });
  const products = await db.catalogProduct.findMany({ orderBy: { id: 'asc' } });
  for (let group = 0; group < 5; group++) await db.procurementRequest.create({ data: { serialNumber: `SCALE-${group}`, department: '行政', handler: '小周', requestDate: date, lines: { create: products.slice(group * 200, (group + 1) * 200).map((p, i) => ({ lineNumber: i + 1, productId: p.id, itemName: p.name, unit: '件', quantityUnits: 2000000n, orderedUnits: 1000000n })) } } });
  const sources = await db.procurementLine.findMany({ orderBy: { id: 'asc' } });
  await db.businessDocument.createMany({ data: products.map(() => ({ kind: 'PURCHASE', date, supplierId: supplier.id, supplierName: supplier.name, settlementMode: 'DETAIL', totalAmountUnits: 1000n })) });
  const docs = await db.businessDocument.findMany({ orderBy: { id: 'asc' } });
  await db.businessLine.createMany({ data: products.map((p, i) => ({ documentId: docs[i].id, requestLineId: sources[i].id, productId: p.id, itemName: p.name, unit: '件', quantityUnits: 1000000n, unitPriceUnits: 100000n, amountUnits: 1000n })) });
  for (let group = 0; group < 10; group++) await db.financialRecord.createMany({ data: products.map(() => ({ kind: 'PAYMENT', date, supplierId: supplier.id, payer: 'COMPANY', amountUnits: 100n })) });
  const records = await db.financialRecord.findMany({ select: { id: true }, orderBy: { id: 'asc' } });
  for (let group = 0; group < 10; group++) await db.financialAllocation.createMany({ data: records.slice(group * 1000, (group + 1) * 1000).map((r, i) => ({ recordId: r.id, documentId: docs[i].id, amountUnits: 100n })) });
  const start = performance.now();
  const page = await finance.settlements(executionQuerySchema.parse({ page: 25 }));
  expect(page.total).toBe(1000); expect(page.items).toHaveLength(20);
  expect(page.items.every(r => r.netPaid === '10.00' && r.payable === '0.00')).toBe(true);
  const queryMs = Math.round(performance.now() - start);
  let batch = await batches.create({ title: '200行集中采购', date, note: '', requestLineIds: sources.slice(0, 200).map(l => l.id) }, randomUUID());
  batch = await batches.save(batch.id, { version: batch.version, title: batch.title, date, note: '', lines: batch.lines.map(l => ({ requestLineId: l.requestLineId!, quantity: '1', unitPrice: '10', supplierId: supplier.id, purchaseLink: null })) }, randomUUID());
  const postStart = performance.now();
  const posted = await batches.confirm(batch.id, batch.version, randomUUID());
  const postMs = Math.round(performance.now() - postStart);
  expect(posted.documents).toHaveLength(1); expect(posted.documents[0].amount).toBe('2000.00');
  expect(posted.lines.every(l => l.remaining === '0')).toBe(true); expect(postMs).toBeLessThan(30_000);
  console.info(`执行规模验收：1000采购/10000付款，对账分页 ${queryMs}ms，200行集中采购 ${postMs}ms`);
}, 60_000);
